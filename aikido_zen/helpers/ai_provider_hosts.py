ALL_HOSTS = AI_PROVIDER_HOSTS + EXTRA_AI_PROVIDER_HOSTS
PROVIDER_BY_HOST = {h: p for h, p in ALL_HOSTS if not h.startswith("*")}
PROVIDER_BY_HOST_SUFFIX = tuple((h[1:], p) for h, p in ALL_HOSTS if h.startswith("*"))


def get_ai_provider(host, default):
    host = host.lower()
    provider = PROVIDER_BY_HOST.get(host)
    if provider:
        return provider
    for suffix, provider in PROVIDER_BY_HOST_SUFFIX:
        label = host[: -len(suffix)]
        if host.endswith(suffix) and label and "." not in label:
            return provider
    return default
