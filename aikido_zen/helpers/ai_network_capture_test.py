def inspect(body, path="/v1/chat/completions", method="POST", status=200, **kwargs):
    if isinstance(body, (dict, list)):
        body = json.dumps(body).encode()
    inspect_ai_response(
        kwargs.get("response", SimpleNamespace()),
        method=method,
        scheme="https",
        host=kwargs.get("host", "api.openai.com"),
        port=None,
        path=path,
        status=status,
        body=body,
    )


